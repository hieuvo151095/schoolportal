/**
 * Generate a pseudo-random hash from string for deterministic mock data
 */
function hashString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

/**
 * Check if target date is in the future relative to today
 */
export function isFutureDate(dateStr: string): boolean {
  // Use Asia/Ho_Chi_Minh or current ISO slice
  const todayStr = new Date().toISOString().slice(0, 10);
  return dateStr > todayStr;
}

/**
 * Retrieve attendance roster for specific class and date.
 * - If future date: returns all unmarked students with no check-in/out data.
 * - If past/today date: returns populated historical attendance data.
 */
export function getAttendanceForDateAndClass(
  dateStr: string,
  classId: string
): StudentAttendance[] {
  const baseStudents = CLASS_STUDENTS_REGISTRY[classId] || CLASS_STUDENTS_REGISTRY['lop-1a1'];
  const isFuture = isFutureDate(dateStr);

  if (isFuture) {
    // Future date: NO attendance data yet
    return baseStudents.map((student) => ({
      ...student,
      arrivalTime: null,
      departureTime: null,
      status: 'unmarked',
      isLate: false,
      temperature: 37.0,
      healthCondition: 'Bình thường',
      notes: '',
      pickupGuardianId: null,
      pickupGuardianName: null,
      refundEligible: false,
    }));
  }

  // Past date: generate deterministic, realistic historical records
  return baseStudents.map((student, idx) => {
    const seed = hashString(`${classId}_${dateStr}_${student.studentId}`);
    const mod = seed % 100;

    // ~85% present, ~10% excused absent, ~5% unmarked
    if (mod < 82) {
      const arrivalMinutes = 15 + (seed % 50); // 07:15 to 08:05
      const hour = arrivalMinutes >= 60 ? '08' : '07';
      const minute = String(arrivalMinutes % 60).padStart(2, '0');
      const arrivalTime = `${hour}:${minute}`;
      const isLate = arrivalTime > '08:00';

      const departureMinutes = 30 + (seed % 45); // 16:30 to 17:15
      const depMinute = String(departureMinutes % 60).padStart(2, '0');
      const departureTime = `16:${depMinute}`;

      const tempDecimal = 4 + (seed % 7); // 36.4 to 37.0
      const temperature = Number(`36.${tempDecimal}`);

      const guardian = student.guardians[0];

      return {
        ...student,
        status: 'present',
        arrivalTime,
        departureTime,
        isLate,
        temperature,
        healthCondition: 'Bình thường',
        pickupGuardianId: guardian?.id || null,
        pickupGuardianName: guardian ? `${guardian.fullName} (${guardian.relationship})` : null,
        refundEligible: false,
      };
    } else if (mod < 94) {
      // Excused absent
      return {
        ...student,
        status: 'excused_absent',
        arrivalTime: null,
        departureTime: null,
        isLate: false,
        temperature: (seed % 2 === 0) ? 37.8 : 37.0,
        healthCondition: (seed % 2 === 0) ? 'Cảm sốt' : 'Bình thường',
        notes: (seed % 2 === 0)
          ? 'Phụ huynh xin nghỉ qua app: bé sốt nhẹ'
          : 'Phụ huynh báo nghỉ có phép do việc gia đình',
        pickupGuardianId: null,
        pickupGuardianName: null,
        refundEligible: true,
      };
    } else {
      // Unmarked
      return {
        ...student,
        status: 'unmarked',
        arrivalTime: null,
        departureTime: null,
        isLate: false,
        temperature: 37.0,
        healthCondition: 'Bình thường',
        notes: '',
        pickupGuardianId: null,
        pickupGuardianName: null,
        refundEligible: false,
      };
    }
  });
}
