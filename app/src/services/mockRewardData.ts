export function getRewardRecordsForClassAndWeek(classId: string, weekNumber: number): StudentRewardRecord[] {
  // Find raw students for this class or fallback to class 1a1
  const classStudents = RAW_MOCK_STUDENTS.filter((s) => s.classId === classId);
  const studentsToUse = classStudents.length > 0 ? classStudents : RAW_MOCK_STUDENTS.filter((s) => s.classId === 'lop-1a1');
  const targetWeek = REWARD_WEEKS_LIST.find((w) => w.weekNumber === weekNumber) || REWARD_WEEKS_LIST[0];

  return studentsToUse.map((student) => {
    const existing = INITIAL_REWARD_RECORDS.find(
      (r) => r.studentId === student.studentId && r.weekNumber === weekNumber
    );

    if (existing) {
      return { ...existing, classId };
    }

    return {
      studentId: student.studentId,
      studentCode: student.studentCode,
      fullName: student.fullName,
      nickname: student.nickname,
      avatarUrl: student.avatarUrl,
      gender: student.gender,
      parentName: student.parentName,
      parentPhone: student.parentPhone,
      classId,
      weekNumber: targetWeek.weekNumber,
      weekRange: targetWeek.weekRange,
      monthWeek: targetWeek.monthWeek,
      isAwarded: true, // Default recommended
      isPublished: false,
      publishedAt: undefined,
      excusedAbsenceCount: 0,
      unexcusedAbsenceCount: 0,
      teacherComment: 'Tuần này bé chăm ngoan, vâng lời cô giáo.',
      monthHistory: generateDefaultMonthHistory(targetWeek.monthWeek, true, 'Tuần này bé chăm ngoan, vâng lời cô giáo.'),
    };
  });
}
